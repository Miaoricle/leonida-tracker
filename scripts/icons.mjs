// Generates src/icons/glyphs.ts with the SVG path data of every glyph named in src/icons/mapping.ts
// (plus a few UI glyphs), so only the icons in use are bundled. Run: npm run icons
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'node_modules/@material-symbols/svg-400/rounded');
const UI = ['check', 'add', 'remove', 'search', 'tune', 'fullscreen', 'fullscreen_exit', 'info', 'close', 'star', 'share', 'chevron_right', 'chevron_left', 'zoom_in', 'my_location', 'settings', 'bar_chart', 'map', 'location_on', 'visibility', 'visibility_off'];
const src = fs.readFileSync(path.join(ROOT, 'src/icons/mapping.ts'), 'utf8');
const names = new Set([...src.matchAll(/:\s*'([a-z0-9_]+)'/g)].map((m) => m[1]).concat(UI, [src.match(/FALLBACK_ICON = '([a-z0-9_]+)'/)[1]]));
const out = {};
for (const n of [...names].sort()) {
  const f = path.join(DIR, `${n}-fill.svg`);
  if (!fs.existsSync(f)) { console.error(`Missing glyph: ${n}`); process.exitCode = 1; continue; }
  const svg = fs.readFileSync(f, 'utf8');
  out[n] = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).join(' ');
}
fs.writeFileSync(path.join(ROOT, 'src/icons/glyphs.ts'),
  `// AUTO-GENERATED by scripts/icons.mjs from Google Material Symbols Rounded (Apache-2.0). Do not edit.\n` +
  `// viewBox: 0 -960 960 960\nexport const GLYPHS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote ${Object.keys(out).length} glyphs`);
