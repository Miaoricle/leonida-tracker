// Dev-only screenshots of the UI at iPhone size. Usage: node scripts/ui-shots.mjs <outDir>  (with `npm run dev` running)
import { chromium, devices } from '@playwright/test';
import fs from 'node:fs';
const out = process.argv[2]; fs.mkdirSync(out, { recursive: true });
const URL = 'http://localhost:5173/leonida-tracker/';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], defaultBrowserType: undefined });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const shot = async (n) => { await p.waitForTimeout(700); await p.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n); };
await p.goto(URL, { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.__leonida, null, { timeout: 60000 });
await shot('1-map');
await p.getByRole('button', { name: 'Filters' }).click();
await shot('2-filters-half');
await p.locator('#filters .sheet-grab').dragTo(p.locator('body'), { targetPosition: { x: 195, y: 60 } }).catch(() => {});
await shot('3-filters-full');
await p.locator('.cat[data-c="hidden-package"] .only').click();
await shot('4-only-hidden-package');
const vis = await p.evaluate(() => window.__leonida.filters.visible());
console.log('visible after Only:', vis);
await p.locator('.cat[data-c="hidden-package"] .next').click();
await p.waitForTimeout(1500); await shot('5-next-unfound');
await p.getByRole('button', { name: 'Search' }).click();
await p.keyboard.type('futbol');
await shot('6-search-futbol');
await p.locator('.search input').fill('xyzzy nothing');
await shot('7-search-empty');
await p.keyboard.press('Escape');
await p.goto(URL + '?feature=stunt-jumps', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.__leonida, null, { timeout: 60000 });
console.log('feature=stunt-jumps ->', await p.evaluate(() => window.__leonida.filters.visible()));
await shot('8-feature-link');
console.log('errors:', errors.length ? errors : 'none');
await b.close();
